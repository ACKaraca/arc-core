//! The automation switch (CORE-APP-020): the setting that starts and stops the local automation
//! socket, the per-client grants remembered in the user settings, the clients and connections of
//! a running socket, and the socket's lifecycle.
//!
//! The setting `automation.enabled` (default off, user scope) decides whether the socket listens.
//! [`Automation::sync`] applies the effective value: on binds a client-table socket in the given
//! directory and adds one client per stored grant; off stops the serving thread, which closes the
//! connections and removes the socket and the token files.
//!
//! Grants are stored in the user settings file as `automation.grants`, an array of tables
//! `{ client = "<label>", permissions = ["read", ...] }`. The key is registered (as
//! [`SettingType::Internal`]) so a system lock applies to it. A grant is a client of the table:
//! the client's identifier in the socket is generated by the application, and its token is the
//! content of the file [`Automation::clients`] reports. [`Automation::grant`] and
//! [`Automation::revoke`] change the settings and the running socket at once. A grant that
//! replaces an earlier one of the same label removes the old client first, which closes its
//! connections and issues a new token. The model of connections is fed by the socket's
//! [`ConnectionObserver`] calls and read from any thread through snapshots.

