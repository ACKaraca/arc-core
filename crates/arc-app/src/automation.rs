    #[test]
    #[cfg(unix)]
    fn clients_and_connections_are_modelled_from_the_observer() {
        use std::io::{BufRead, BufReader, Write};
        use std::os::unix::net::UnixStream;

        let d = dir("automation-model");
        let run = d.join("run");
        let mut store = fresh();
        let mut automation = Automation::new();
        automation
            .grant(&mut store, None, "reader", [Permission::Read].into())
            .unwrap();
        automation
            .grant(
                &mut store,
                None,
                "editor",
                [Permission::Read, Permission::Edit].into(),
            )
            .unwrap();
        let changes = automation.subscribe();
        automation
            .start(&run, &product(), None, no_documents(), &grants(&store))
            .unwrap();
        let socket = automation.socket_path().unwrap().to_owned();
        let clients = automation.clients();
        assert_eq!(clients.len(), 2);

        let connect = |client: &ClientInfo| {
            let token = std::fs::read_to_string(&client.token_path).unwrap();
            let mut conn = UnixStream::connect(&socket).unwrap();
            writeln!(
                conn,
                "{{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"arc.authenticate\",\"params\":{{\"token\":\"{token}\",\"clientName\":\"{}\"}}}}",
                client.client_id
            )
            .unwrap();
            let mut reader = BufReader::new(conn.try_clone().unwrap());
            let mut answer = String::new();
            reader.read_line(&mut answer).unwrap();
            assert!(answer.contains("result"), "{answer}");
            (conn, reader)
        };
        let (first, first_reader) = connect(&clients[0]);
        let (second, second_reader) = connect(&clients[1]);
        // A handshake is answered after `opened` ran, so the model already lists both.
        let connections = automation.connections();
        assert_eq!(connections.len(), 2);
        let by_label = |label: &str| connections.iter().find(|c| c.label == label).unwrap();
        assert_eq!(by_label("reader").permissions, [Permission::Read].into());
        assert_eq!(
            by_label("editor").permissions,
            [Permission::Read, Permission::Edit].into()
        );

        // The first connection ends; the model drops it once `closed` ran, which is announced.
        drop(first);
        drop(first_reader);
        while automation.connections().len() != 1 {
            changes.recv().unwrap();
        }
        let left = automation.connections();
        assert_eq!(left.len(), 1);
        assert_eq!(left[0].client_id, clients[1].client_id);
        drop(second);
        drop(second_reader);
        automation.stop();
    }

    #[test]
    #[cfg(unix)]
    #[allow(
        clippy::too_many_lines,
        reason = "one scenario: grant, use, revoke, refuse"
    )]
    fn a_revoked_client_is_refused_at_once_and_other_clients_keep_working() {
        use std::io::{BufRead, BufReader, Write};
        use std::os::unix::net::UnixStream;

        struct Session {
            conn: UnixStream,
            reader: BufReader<UnixStream>,
        }
        impl Session {
            /// Sends one request and reads its answer; `None` when the connection has ended.
            fn ask(&mut self, line: &str) -> Option<serde_json::Value> {
                writeln!(self.conn, "{line}").ok()?;
                let mut answer = String::new();
                match self.reader.read_line(&mut answer) {
                    Ok(0) | Err(_) => None,
                    Ok(_) => serde_json::from_str(&answer).ok(),
                }
            }
        }
        // Connects with a token and client identifier, answering the handshake's answer.
        let open = |socket: &Path, token: &str, client_id: &str| {
            let conn = UnixStream::connect(socket).unwrap();
            let reader = BufReader::new(conn.try_clone().unwrap());
            let mut session = Session { conn, reader };
            let answer = session.ask(&format!(
                "{{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"arc.authenticate\",\"params\":{{\"token\":\"{token}\",\"clientName\":\"{client_id}\"}}}}"
            ));
            (session, answer)
        };
        let initialize = |session: &mut Session, permissions: &str| {
            let answer = session.ask(&format!(
                "{{\"jsonrpc\":\"2.0\",\"id\":2,\"method\":\"arc.initialize\",\"params\":{{\"clientName\":\"t\",\"protocolVersions\":{{\"min\":\"1.0\",\"max\":\"1.0\"}},\"permissions\":[{permissions}]}}}}"
            ));
            assert!(answer.is_some_and(|a| a.get("result").is_some()));
        };
        let edit = r#"{"jsonrpc":"2.0","id":3,"method":"command.run","params":{"document":"main","command":"shell.layer.create","params":{"name":"walls"}}}"#;
        let ping = r#"{"jsonrpc":"2.0","id":4,"method":"arc.ping","params":{}}"#;

        let d = dir("automation-revoke");
        let mut store = fresh();
        let mut automation = Automation::new();
        automation
            .grant(
                &mut store,
                None,
                "editor",
                [Permission::Read, Permission::Edit].into(),
            )
            .unwrap();
        automation
            .grant(
                &mut store,
                None,
                "steady",
                [Permission::Read, Permission::Edit].into(),
            )
            .unwrap();
        let changes = automation.subscribe();
        let product = product();
        let documents = BTreeMap::from([(
            "main".to_owned(),
            Document::new(product.types.clone(), product.evaluators.clone()).unwrap(),
        )]);
        automation
            .start(&d.join("run"), &product, None, documents, &grants(&store))
            .unwrap();
        let socket = automation.socket_path().unwrap().to_owned();
        let clients = automation.clients();
        let editor = clients
            .iter()
            .find(|c| c.label == "editor")
            .unwrap()
            .clone();
        let steady = clients
            .iter()
            .find(|c| c.label == "steady")
            .unwrap()
            .clone();
        // The token file is removed by the revocation, so the token is read first.
        let editor_token = std::fs::read_to_string(&editor.token_path).unwrap();
        let steady_token = std::fs::read_to_string(&steady.token_path).unwrap();

        let (mut edit_session, answer) = open(&socket, &editor_token, &editor.client_id);
        assert!(answer.is_some_and(|a| a.get("result").is_some()));
        initialize(&mut edit_session, "\"read\",\"edit\"");
        let created = edit_session.ask(edit).unwrap();
        assert!(created.get("result").is_some(), "the edit runs: {created}");

        let (mut steady_session, _) = open(&socket, &steady_token, &steady.client_id);
        initialize(&mut steady_session, "\"read\",\"edit\"");
        assert!(
            steady_session
                .ask(ping)
                .is_some_and(|a| a.get("result").is_some())
        );

        assert!(automation.revoke(&mut store, None, "editor").unwrap());
        assert!(
            edit_session.ask(edit).is_none(),
            "the revoked connection gets no further answer"
        );
        let (_, refused) = open(&socket, &editor_token, &editor.client_id);
        assert_eq!(
            refused.unwrap()["error"]["data"]["code"],
            "cmd.socket.unauthorized",
            "a new connection with the old token is refused"
        );
        assert!(
            steady_session
                .ask(ping)
                .is_some_and(|a| a.get("result").is_some()),
            "the other client keeps working"
        );
        // The revoked session ends on its own thread; its end is announced to the subscriber.
        while automation.connections().len() != 1 {
            changes.recv().unwrap();
        }
        let connected = automation.connections();
        assert_eq!(
            connected[0].client_id, steady.client_id,
            "only the steady client is connected"
        );
        automation.stop();
    }

