//! The mapping between typed record fields and groups.

use arc_base::{Limits, Result};

use crate::error::Position;
use crate::group::{Group, Handle, Value, ValueKind, Version, value_kind};
use crate::loss::LossLog;

/// One typed field stored under a base group code. Points use the base code and the codes 10
/// and 20 above it for their coordinates; lists push an element at the base code.
pub(crate) trait Field {
    /// Claims `g` when it belongs to this field.
    fn take(&mut self, code: i16, g: &Group) -> bool;
    /// Writes the field.
    fn put(&self, code: i16, out: &mut Vec<Group>);
}

/// The fields of a record type, generated by [`fields!`].
pub(crate) trait Fields {
    fn take_field(&mut self, g: &Group) -> bool;
    fn put_fields(&self, out: &mut Vec<Group>);
}

/// The context of reading one record.
pub(crate) struct Cx<'a> {
    pub(crate) version: Version,
    pub(crate) limits: &'a Limits,
    pub(crate) at: Position,
}

/// The context of writing.
pub(crate) struct WriteCx<'a> {
    pub(crate) version: Version,
    pub(crate) loss: &'a mut LossLog,
}

/// A record type with its group mapping.
pub(crate) trait Body: Fields {
    /// Claims groups that need sequence state or several following groups.
    fn take_more(
        &mut self,
        _g: &Group,
        _cur: &mut Cursor<'_>,
        _cx: &Cx<'_>,
        _sub: &str,
    ) -> Result<bool> {
        Ok(false)
    }

    /// Writes the record's own groups, including its subclass markers.
    fn put(&self, out: &mut Vec<Group>, _w: &mut WriteCx<'_>) -> Result<()> {
        self.put_fields(out);
        Ok(())
    }
}

/// A position in the groups of one record.
pub(crate) struct Cursor<'a> {
    groups: &'a [Group],
    pos: usize,
}

impl<'a> Cursor<'a> {
    pub(crate) fn new(groups: &'a [Group]) -> Self {
        Self { groups, pos: 0 }
    }

    pub(crate) fn next(&mut self) -> Option<&'a Group> {
        let g = self.groups.get(self.pos)?;
        self.pos += 1;
        Some(g)
    }

    pub(crate) fn peek(&self) -> Option<&'a Group> {
        self.groups.get(self.pos)
    }

    pub(crate) fn rest(&mut self) -> &'a [Group] {
        let rest = self.groups.get(self.pos..).unwrap_or_default();
        self.pos = self.groups.len();
        rest
    }
}

impl Field for f64 {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        match g.value {
            Value::Double(v) if g.code == code => {
                *self = v;
                true
            }
            _ => false,
        }
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        out.push(Group::double(code, *self));
    }
}

macro_rules! int_field {
    ($t:ty) => {
        impl Field for $t {
            fn take(&mut self, code: i16, g: &Group) -> bool {
                match g.value {
                    Value::Int(v) if g.code == code => match <$t>::try_from(v) {
                        Ok(v) => {
                            *self = v;
                            true
                        }
                        Err(_) => false,
                    },
                    _ => false,
                }
            }
            fn put(&self, code: i16, out: &mut Vec<Group>) {
                out.push(Group::int(code, i64::from(*self)));
            }
        }
    };
}
int_field!(i16);
int_field!(i32);

impl Field for bool {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        if g.code != code {
            return false;
        }
        match g.value {
            Value::Bool(b) => *self = b,
            Value::Int(v) => *self = v != 0,
            _ => return false,
        }
        true
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        out.push(if value_kind(code) == Some(ValueKind::Bool) {
            Group {
                code,
                value: Value::Bool(*self),
            }
        } else {
            Group::int(code, i64::from(*self))
        });
    }
}

impl Field for String {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        match &g.value {
            Value::Text(text) if g.code == code => {
                text.clone_into(self);
                true
            }
            _ => false,
        }
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        out.push(Group::text(code, self.clone()));
    }
}

impl Field for Handle {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        match g.as_handle() {
            Some(h) if g.code == code => {
                *self = h;
                true
            }
            _ => false,
        }
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        out.push(Group::text(code, self.to_hex()));
    }
}

/// A point of `N` coordinates under the codes `base`, `base + 10`, `base + 20`.
fn coordinate(base: i16, g: &Group, n: usize) -> Option<(usize, f64)> {
    let Value::Double(v) = g.value else {
        return None;
    };
    let offset = g.code.checked_sub(base)?;
    let axis = match offset {
        0 => 0,
        10 => 1,
        20 => 2,
        _ => return None,
    };
    (axis < n).then_some((axis, v))
}

impl<const N: usize> Field for [f64; N] {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        match coordinate(code, g, N) {
            Some((axis, v)) => self.get_mut(axis).map(|slot| *slot = v).is_some(),
            None => false,
        }
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        let mut axis_code = code;
        for v in self {
            out.push(Group::double(axis_code, *v));
            axis_code += 10;
        }
    }
}

impl<T: Field + Default> Field for Option<T> {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        match self {
            Some(v) => v.take(code, g),
            None => {
                let mut v = T::default();
                let claimed = v.take(code, g);
                if claimed {
                    *self = Some(v);
                }
                claimed
            }
        }
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        if let Some(v) = self {
            v.put(code, out);
        }
    }
}

impl Field for Vec<f64> {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        let mut v = 0.0;
        let claimed = v.take(code, g);
        if claimed {
            self.push(v);
        }
        claimed
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        for v in self {
            v.put(code, out);
        }
    }
}

impl Field for Vec<Handle> {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        let mut h = Handle::default();
        let claimed = h.take(code, g);
        if claimed {
            self.push(h);
        }
        claimed
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        for h in self {
            h.put(code, out);
        }
    }
}

impl<const N: usize> Field for Vec<[f64; N]> {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        match coordinate(code, g, N) {
            Some((0, v)) => {
                let mut p = [0.0; N];
                if let Some(x) = p.first_mut() {
                    *x = v;
                }
                self.push(p);
                true
            }
            Some((axis, v)) => self
                .last_mut()
                .and_then(|p| p.get_mut(axis))
                .map(|slot| *slot = v)
                .is_some(),
            None => false,
        }
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        for p in self {
            p.put(code, out);
        }
    }
}

/// Binary data split over chunks of at most 127 bytes.
impl Field for Vec<u8> {
    fn take(&mut self, code: i16, g: &Group) -> bool {
        match &g.value {
            Value::Bytes(bytes) if g.code == code => {
                self.extend_from_slice(bytes);
                true
            }
            _ => false,
        }
    }
    fn put(&self, code: i16, out: &mut Vec<Group>) {
        for chunk in self.chunks(127) {
            out.push(Group {
                code,
                value: Value::Bytes(chunk.to_vec()),
            });
        }
    }
}

/// The element count written before a list.
pub(crate) fn count(code: i16, len: usize) -> Group {
    Group::int(code, i64::try_from(len).unwrap_or(i64::MAX))
}

/// Declares a record type: a struct with documented public fields and its [`Fields`] mapping.
///
/// Each field is `name: Type = code`, optionally preceded by `["Marker"]` (a subclass marker
/// written before it) and followed by `(count N)` (an element count written before a list and
/// dropped on reading). A field without `= code` is mapped by hand.
macro_rules! fields {
    (
        $(#[$sm:meta])*
        pub struct $name:ident {
            $(
                $(#[$fm:meta])*
                $([$mark:literal])?
                $f:ident : $t:ty $(= $code:literal $((count $cnt:literal))?)?
            ),* $(,)?
        }
    ) => {
        $(#[$sm])*
        #[derive(Debug, Clone, PartialEq, Default)]
        pub struct $name {
            $( $(#[$fm])* pub $f: $t, )*
        }

        impl crate::fields::Fields for $name {
            #[allow(unused_variables)]
            fn take_field(&mut self, g: &crate::group::Group) -> bool {
                $( $(
                    $( if g.code == $cnt { return true; } )?
                    if crate::fields::Field::take(&mut self.$f, $code, g) {
                        return true;
                    }
                )? )*
                false
            }

            #[allow(unused_variables)]
            fn put_fields(&self, out: &mut Vec<crate::group::Group>) {
                $(
                    $( out.push(crate::group::Group::marker($mark)); )?
                    $(
                        $( out.push(crate::fields::count($cnt, self.$f.len())); )?
                        crate::fields::Field::put(&self.$f, $code, out);
                    )?
                )*
            }
        }
    };
}

pub(crate) use fields;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn points_take_their_three_codes() {
        let mut p = [0.0; 3];
        assert!(p.take(10, &Group::double(10, 1.0)));
        assert!(p.take(10, &Group::double(20, 2.0)));
        assert!(p.take(10, &Group::double(30, 3.0)));
        assert!(!p.take(10, &Group::double(11, 3.0)));
        assert_eq!(p, [1.0, 2.0, 3.0]);
        let mut q = [0.0; 2];
        assert!(!q.take(10, &Group::double(30, 3.0)));
    }

    #[test]
    fn lists_push_at_the_base_code_and_fill_the_last_element() {
        let mut list: Vec<[f64; 2]> = Vec::new();
        assert!(!list.take(10, &Group::double(20, 1.0)));
        assert!(list.take(10, &Group::double(10, 1.0)));
        assert!(list.take(10, &Group::double(20, 2.0)));
        assert_eq!(list, vec![[1.0, 2.0]]);
    }

    #[test]
    fn integers_out_of_range_are_not_claimed() {
        let mut v = 0i16;
        assert!(!v.take(70, &Group::int(70, 70_000)));
        let mut b = false;
        assert!(b.take(290, &Group::int(290, 2)) && b);
    }
}
